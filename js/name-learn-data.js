function toHira(s){
  return s.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60))
          .replace(/[ー]/g, 'ー');
}
function isKana(s){
  return /^[ぁ-ゖァ-ヺーー\s]+$/.test(s);
}

/**
 * かな列をハングル音節配列に変換。
 * ん→終声ㄴ / っ→終声ㅅ / 長音(ー・重なる母音)→省略
 */
function kanaToHangul(kanaRaw){
  const kana = toHira(kanaRaw).replace(/\s+/g, '');
  const out = [];
  let i = 0;
  while (i < kana.length){
    const ch = kana[i];

    // 長音記号は省略（とーきょー → 도쿄 のように）
    if (ch === 'ー'){ i++; continue; }

    // 撥音 ん → 直前の音節に終声ㄴ
    if (ch === 'ん'){
      if (out.length){
        const d = decomp(out[out.length-1]);
        if (d && !d.jong) out[out.length-1] = comp(d.cho, d.jung, 'ㄴ');
      }
      i++; continue;
    }
    // 促音 っ → 直前の音節に終声ㅅ
    if (ch === 'っ'){
      if (out.length){
        const d = decomp(out[out.length-1]);
        if (d && !d.jong) out[out.length-1] = comp(d.cho, d.jung, 'ㅅ');
      }
      i++; continue;
    }
    // 長母音: 直前の母音が ㅗ/ㅛ/ㅜ/ㅠ で 次が う → 省略（とうきょう→도쿄）。ㅗ+お も省略。
    // ただし う/お の直後がさらに母音なら、それは長音ではなく独立したモーラ。
    //   いのうえ（井上）= い+の+う+え → 이노우에（×이노에）
    if (out.length){
      const d = decomp(out[out.length-1]);
      const next = kana[i+1] || '';
      const nextIsVowel = next !== '' && 'あいうえお'.includes(next);
      if (d && !nextIsVowel){
        if (ch === 'う' && ['ㅗ','ㅛ','ㅜ','ㅠ'].includes(d.jung)){ i++; continue; }
        if (ch === 'お' && d.jung === 'ㅗ'){ i++; continue; }
        if (ch === 'あ' && d.jung === 'ㅏ'){ i++; continue; }
      }
    }

    const two = kana.substr(i, 2);
    if (KANA2[two]){ out.push(KANA2[two]); i += 2; continue; }
    if (KANA1[ch]) { out.push(KANA1[ch]);  i += 1; continue; }
    i++; // 未知文字はスキップ
  }
  return out;
}

