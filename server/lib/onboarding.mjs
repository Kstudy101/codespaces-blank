/* ==================================================================
   lib/onboarding.mjs — 始める前に 3 つだけ確かめる

   この講座は「あなたの名前」と「あなたの四柱」で進む。だから
   始める前に、その 2 つが本人のものかを確かめないといけない。
   確かめずに始めると、101 日ぶんが別人のものになる ── しかも
   名前も運勢も「それらしい形」で出るので、受け取った側からは
   間違いだと分からない。

     1  名前     ウェブで入れた名前で呼ぶか、別の名前にするか
     2  生年月日 ウェブに入れたものが本人のものか
     3  コース   初級 / 中級 / 上級

   【状態の列を作らなかった理由】
   「今どの段まで進んだか」を列で持つと、実際の中身（name_source が
   入っているか、birth_confirmed が立っているか、track が入っているか）と
   二重に真実ができる。片方だけ進んだ状態は必ず起きる（送信が失敗した、
   利用者がボタンを押さずに 3 日置いた）ので、そのときどちらを信じるかを
   決められない。

   なので段は持たず、毎回そのつど中身から導く（nextStep）。
   導けるものを保存しない、が唯一ずれない書き方。

   【なぜウェブの生年月日を疑うのか】
   サイトの診断は「試しに入れてみる」場所でもある。実際、名前も
   生年月日も適当に入れて結果だけ見る使い方ができる ── そのために
   ログインを要らなくしてある。その値のまま LINE へ引き継ぐと、
   毎朝 101 回、別人の運勢が届く。
   ================================================================== */
import { TRACKS, TRACK_LABELS } from "./repo/learning.mjs";

/* 診断ページ。名前を入れ直す道はここしか無い（下の注記を参照）。 */
const SITE_URL = process.env.SITE_URL || "https://www.kstudy101.jp";

export const STEPS = Object.freeze(["name", "birth", "track"]);


/* ---- 次に訊くこと --------------------------------------------------
   listDeliverable の 1 行をそのまま渡せる形にしてある。
   足りない列があっても落ちない（undefined は「無い」と同じ扱い）。

   返すのは 1 つだけ。3 つまとめて訊くと、答えが 3 つ返ってくるまで
   何も始まらず、途中で止めた人がどこまで答えたのか分からなくなる。 */
export function nextStep(u = {}) {
  /* 1. 名前。**選べるときにだけ**訊く。
     ウェブの名前が無い人（友だち追加だけ）は、そもそも選択肢が
     無いので訊かない ── その人は push-daily の名前案内が拾う。
     LINE の表示名が取れなかった人も同じで、比べる相手が無い。 */
  if (!u.name_source && u.name_kr && u.display_name) return "name";

  /* 2. 生年月日。四柱がある人にだけ。
     無い人に「合っていますか」と訊いても見せるものが無い。 */
  if (u.birth_date && !u.birth_confirmed) return "birth";

  /* 3. コース。 */
  if (!u.track) return "track";

  return null;
}


/* ---- ボタン --------------------------------------------------------
   quickReply を使う。Flex Message でも作れるが、こちらは本文が
   ただのテキストのままなので、通知のプレビューに用件が出る ──
   Flex だと「メッセージが届きました」としか出ない。

   label は 20 字まで。超えると LINE が 400 を返し、その人だけ
   案内が届かないまま止まる。ここで切っておく。 */
function quick(items) {
  return {
    items: items.slice(0, 13).map(({ label, data, displayText }) => ({
      type: "action",
      action: {
        type: "postback",
        label: String(label).slice(0, 20),
        data,
        /* 押した本人のトークに、選んだものが残るようにする。
           残らないと、あとから見返したときに何を選んだのか分からない。 */
        displayText: displayText || String(label).slice(0, 20)
      }
    }))
  };
}


/* ---- 1. サービスの案内 ---------------------------------------------
   連携した直後に 1 度だけ送る。

   これまで、サイトを通ってきた人には**何も送っていなかった**
   （handlers/follow.mjs は名前が無い人にしか返さない）。連携が
   成功しても LINE 側は無言で、最初のメッセージが翌朝の「1 日目」
   だった ── 何に登録したのか分からないまま本文が始まる。

   長いが 1 通に収める。分けると、読み飛ばした人が「コースを選ぶ」に
   たどり着けない。 */
export function serviceGuide({ nameJa = null } = {}) {
  const you = nameJa ? `${nameJa}さん` : "あなた";
  return {
    type: "text",
    text: [
      "連携できました。ここから毎日おとどけします。",
      "",
      "──────────",
      "📖 この講座について",
      "──────────",
      `韓国語を、${you}の**名前**と**四柱**で学びます。`,
      "教科書の「ミンスさん」ではなく、例文の主語があなたです。",
      "",
      "・会話文はあなたが「私」として登場します",
      "　場面（買い物・道をたずねる・自己紹介…）ごとに、",
      "　あなたの名前で言えるようになります",
      "・韓国式の占い（사주・운세・기운）が毎朝つきます",
      "　その日の運勢を韓国語で読むので、言葉と一緒に身につきます",
      "",
      "──────────",
      "🕖 1日のながれ",
      "──────────",
      "朝 7時　今日の運勢 ＋ 文法 ＋ 会話 ＋ 単語3語",
      "夕 6時　その文法をもう一度（復習）",
      "",
      "※ 進むのは朝の便だけです。夕方の復習と節目のクイズは",
      "　 おまけなので、お持ちの日数は減りません。",
      "",
      "──────────",
      "📚 コース",
      "──────────",
      "初級 / 中級 / 上級 の3つ。それぞれ101日ぶんの別の講座です。",
      "（途中で変えられないので、最初に選びます）",
      "",
      "このあと、順にお訊きします。"
    ].join("\n")
  };
}


/* ---- 2. 名前をどちらにするか ---------------------------------------
   ウェブで入れた名前と、LINE の表示名を並べて見せる。

   【LINE の名前を選んだらどうなるか】
   その場では確定できない。韓国語表記（다나카）を作るには、
   サイトが持っている読み仮名とハングルの対応表（index.html の
   hanja_db / kanji.json）が要る。サーバーには置いていない ──
   .cpanel.yml が写すのは saju.js / fortune.js / solar-terms.json の
   3 つだけで、変換表は入っていない。

   写して 2 部にすると、ウェブと LINE で同じ名前が違うハングルに
   なりうる。それは運勢の食い違い（lib/fortune.mjs の注記）と同じ
   性質の壊れ方で、並べて見るまで気づけない。

   なので「LINE の名前で」を選んだ人には、その名前でもう一度
   診断してもらう。遠回りに見えるが、変換はサイトの 1 部だけが行う、
   を守る唯一の形になっている。 */
export function askName({ webName, webNameKr = null, lineName }) {
  /* ハングル表記も並べる。会話文に出るのはこちらなので、
     漢字だけ見せて選ばせると「そう読まれるとは思わなかった」が
     101 日たってから分かる。 */
  const web = webNameKr && webNameKr !== webName ? `${webName}（${webNameKr}）` : String(webName);

  return {
    type: "text",
    text: [
      "① お名前の確認",
      "",
      "この講座は、お名前がそのまま教材になります。",
      "毎日の会話文に、この名前で登場します。",
      "",
      `　サイトで入力　${web}`,
      `　LINEの表示名　${lineName}`,
      "",
      "どちらのお名前で進めますか？"
    ].join("\n"),
    quickReply: quick([
      { label: `${String(webName).slice(0, 12)}で`, data: "action=name&use=web",
        displayText: `${webName} で進めます` },
      { label: "LINEの名前にする", data: "action=name&use=line",
        displayText: "LINEの名前にします" }
    ])
  };
}

/* LINE の名前を選んだ人への返し。サイトへ送る。 */
export function nameRedo() {
  return {
    type: "text",
    text: [
      "承知しました。",
      "",
      "お名前のハングル表記は、サイトの診断でつくります。",
      "（読み方から一文字ずつ変換するので、こちらでは作れません）",
      "",
      "▼ 使いたいお名前で、もう一度どうぞ（1分ほど）",
      SITE_URL,
      "",
      "診断のあと「LINEで受け取る」を押すと、こちらに反映されます。"
    ].join("\n")
  };
}


/* ---- 3. 生年月日の確認 ---------------------------------------------
   時刻まで見せる。四柱は時柱で変わるので、日付だけ合っていても
   時刻が「とりあえず 0 時」だと別の四柱になる。 */
export function askBirth({ birthDate, birthTime = null }) {
  const t = birthTime
    ? `${String(birthTime).slice(0, 5)} ごろ`
    : "時刻は未入力（時柱なしで占います）";

  return {
    type: "text",
    text: [
      "② 生年月日の確認",
      "",
      "毎朝の運勢は、この生年月日から四柱を立てて出します。",
      "サイトでお試しの値を入れていた場合は、ここで直せます。",
      "",
      `　${birthDate}`,
      `　${t}`,
      "",
      "こちらはご本人のものですか？"
    ].join("\n"),
    quickReply: quick([
      { label: "はい、これで", data: "action=birth&ok=1",
        displayText: "はい、この生年月日で" },
      { label: "入れ直したい", data: "action=birth&ok=0",
        displayText: "入れ直します" }
    ])
  };
}

/* 入れ直す人への返し。名前と同じくサイトへ戻す ── 生年月日だけを
   LINE で受け取る道を作ると、日付の書き方（1995/4/12・H7.4.12・
   1995-04-12）を LINE 側でも解釈することになり、サイトと 2 通りの
   読み取りができる。ずれたときに四柱が変わる。 */
export function birthRedo() {
  return {
    type: "text",
    text: [
      "承知しました。",
      "",
      "▼ 本当の生年月日で、もう一度どうぞ",
      SITE_URL,
      "",
      "生まれた時刻が分かる場合は入れてください。",
      "四柱の「時柱」が決まるので、運勢が細かくなります。",
      "分からなければ空のままで大丈夫です。"
    ].join("\n")
  };
}


/* ---- 4. コース選択 -------------------------------------------------
   3 つとも別の 101 日。選び直せないことを先に書く ── 20 日目で
   「やっぱり中級に」と言われても、そこから中級の 1 日目を送ると
   買った日数が合わなくなる。 */
export function askTrack() {
  return {
    type: "text",
    text: [
      "③ コースを選んでください",
      "",
      "初級（초급）",
      "　ハングルの読み書きから。「저는 ○○입니다」で始めます",
      "　韓国語がはじめての方",
      "",
      "中級（중급）",
      "　文と文をつなぐ・敬語・場面ごとの会話",
      "　あいさつと自己紹介ができる方",
      "",
      "上級（고급）",
      "　込み入った言い回し・書き言葉・ニュースの韓国語",
      "　日常会話に困らない方",
      "",
      "それぞれ101日間の別の講座です。",
      "あとから変えられませんので、ゆっくりお選びください。"
    ].join("\n"),
    quickReply: quick(TRACKS.map((t) => ({
      label: `${TRACK_LABELS[t].ja}（${TRACK_LABELS[t].kr}）`,
      data: `action=track&pick=${t}`,
      displayText: `${TRACK_LABELS[t].ja} を選びます`
    })))
  };
}

/* 選び終わったあと。翌朝から始まることを言う ── 押した直後に
   何も来ないと、選べたのかどうか分からない。 */
export function trackChosen(track) {
  const l = TRACK_LABELS[track];
  return {
    type: "text",
    text: [
      `${l.ja}（${l.kr}）を承りました。`,
      "",
      "明日の朝7時に、1日目をおとどけします。",
      "夕方6時には、その日の文法をもう一度お送りします。",
      "",
      "「今何日目？」と送っていただければ、進み具合をお答えします。"
    ].join("\n")
  };
}

/* もう選び終わっている人がもう一度押した。 */
export function trackAlready(track) {
  const l = TRACK_LABELS[track];
  return {
    type: "text",
    text: `すでに ${l.ja}（${l.kr}）で始まっています。コースの変更はできません。`
  };
}


/* ---- 次の 1 通を作る ------------------------------------------------
   nextStep が返した段の文面を作る。作れないとき（訊く必要が無い）は
   null を返すので、呼ぶ側は送らずに済む。 */
export function messageForStep(step, u = {}) {
  if (step === "name") {
    return askName({
      webName: u.name_kanji || u.name_kr,
      webNameKr: u.name_kr,
      lineName: u.display_name
    });
  }
  if (step === "birth") {
    return askBirth({ birthDate: String(u.birth_date).slice(0, 10), birthTime: u.birth_time });
  }
  if (step === "track") return askTrack();
  return null;
}
