/* ==================================================================
   3b. 常用漢字データベース（外部 kanji.json・2136字）
   ------------------------------------------------------------------
   上の HANJA は手書きの学習コンテンツ（意味・単語・例文）。
   こちらは網羅用の参照データで、韓国漢字音と訓音（例：「밭 전」）を持つ。
   件数が多いので本体には埋め込まず、読み込み後に併用する。
   取得に失敗しても HANJA だけで動作する。
   ================================================================== */
let KDB = null;              /* {char:[韓国音, 訓音]} */
let KYU = null;              /* 旧字体 → 新字体 */
const kdbReady = (typeof fetch === 'function'
  ? fetch('kanji.json').then(r => r.ok ? r.json() : null)
  : Promise.resolve(null))
  .then(d => { if (d && d.k){ KDB = d.k; KYU = d.kyu || {}; } })
  .catch(() => { /* オフライン等。HANJA のみで続行する */ });

/* 旧字体で書かれていれば新字体に寄せる（齋→斎、櫻→桜 など） */
function normKanji(c){
  return (KYU && KYU[c]) ? KYU[c] : c;
}
/* 踊り字を開く。「佐々木」は「佐佐木」として読む（々 は直前の字の繰り返し）。
   コードポイント単位で扱う。文字列末尾を slice すると
   基本多言語面外の漢字（𠮟 など）でサロゲートペアが割れてしまうため。 */
function expandRep(s){
  const out = [];
  for (const c of s) out.push((c === '々' || c === '〻') ? (out[out.length-1] || '') : c);
  return out.join('');
}
/* 1文字の情報を引く。手書きデータを優先し、無ければ DB を見る。
   手書き側は名前で使う読みを選んであるので、多音字（楽=락/악）はこちらが勝つ。 */
function lookup(c){
  const n = normKanji(c);
  const cur = HANJA[c] || HANJA[n];
  const db  = KDB ? (KDB[c] || KDB[n]) : null;
  if (!cur && !db) return null;
  return {
    k:   cur ? cur.k  : db[0],          /* 韓国漢字音 */
    m:   cur ? cur.m  : '',             /* 日本語での意味 */
    hun: db  ? db[1]  : '',             /* 韓国式の訓音「밭 전」 */
    w:   cur ? cur.w  : null,           /* 対応する韓国語の固有語 */
    wj:  cur ? cur.wj : null,
    ex:  cur ? cur.ex : null,
    old: n !== c ? n : null             /* 旧字体で入力された場合の新字体 */
  };
}

