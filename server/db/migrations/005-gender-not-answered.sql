--
-- 「答えない」が通らなかった問題（지시서⑩・2026-08-06 승인）。
--
-- gender の 'U' が「未質問」と「答えないと答えた」を兼ねていた。
-- 段階は値から導出する設計なので、答えても値が変わらない選択肢は
-- 沈黙と区別がつかず、同じ質問が永遠に出る ── 온보딩이 거기서
-- 막힌다（실사용 보고）。
--
--   'M' / 'F' … 答えた
--   'U'       … まだ訊いていない（既定。サイト経由もここ）
--   'N'       … 訊かれて、答えないと答えた
--
-- 判定式（PENDING.bgender の gender === 'U'）は**変えない** ──
-- 'N' が入れば式が自然に偽になる。それがこの処方の要点で、
-- 意味だけが正確になる。既存の 'U' は一括変換しない（§4）──
-- サイト経由の「未質問」まで「答えない」に化けるのは、事実でない
-- ものを DB に刻む仕事。
--
-- 코드 측 화이트리스트（postback / link normalizeProfile）와
-- verify-server 가 이 나열을 대조한다。
ALTER TABLE saju_profiles
  MODIFY COLUMN gender ENUM('M','F','U','N') NOT NULL DEFAULT 'U';
